// Marketing campaign report: visits by `?ref=` link tag, how many of them searched, compared with untagged traffic.
// Writes the generated part of docs/campaigns.md (between the markers); the hand-written findings around it stay.
//
//   npm run umami:campaigns                       from the earliest ref in the data until now
//   npm run umami:campaigns -- --from 2026-08-01
//   npm run umami:campaigns -- --dry              print the report instead of writing the file
//
// Campaign names, channels, costs and typo aliases live in scripts/umami/campaigns.json.
// Auth is the same share link as fetch.mjs (UMAMI_SHARE_URL in .env).
//
// Attribution: a visit (Umami closes a visit after 30 min of inactivity) belongs to the ref found on its entry
// page. The ref is first-touch and per visit: a later visit of the same person without a ref counts as untagged
// (it shows up under "returned" of the ref visit, not as a second campaign visit).
import { readFile, writeFile } from 'node:fs/promises'
import { parseArgs } from 'node:util'
import { dayKey } from './digest.mjs'

// custom events (search, FAQ, ...) exist since 03.07.2026; before that a visit cannot show any interaction
const EVENTS_TRACKING_DATE = '2026-07-03'

const SHARE_URL = process.env.UMAMI_SHARE_URL
const BASE = process.env.UMAMI_API_URL ?? 'https://cloud.umami.is/analytics/eu/api'
const REPORT = new URL('../../docs/campaigns.md', import.meta.url)
const START = '<!-- campaigns:start (generated by npm run umami:campaigns, do not edit by hand) -->'
const END = '<!-- campaigns:end -->'
// below this many visits a rate says nothing
const MIN_VISITS = 20

const { values: args } = parseArgs({
  options: { from: { type: 'string' }, dry: { type: 'boolean', default: false }, hostname: { type: 'string', default: 'neq.localhost' } }
})
if (!SHARE_URL) {
  console.error('Set UMAMI_SHARE_URL in .env (Umami Cloud -> website settings -> Share URL).')
  process.exit(1)
}

const registry = JSON.parse(await readFile(new URL('./campaigns.json', import.meta.url), 'utf8'))
const aliases = registry.aliases ?? {}

// ---- fetch ----
const shareId = new URL(SHARE_URL).pathname.split('/').filter(Boolean).at(-1)
const share = await (await fetch(`${BASE}/share/${shareId}`)).json()
if (!share.token) throw new Error('share link rejected, check UMAMI_SHARE_URL')
const HEADERS = { accept: 'application/json', 'x-umami-share-token': share.token, 'x-umami-share-context': '1' }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
let last = 0
async function api(path, params, attempt = 0) {
  // Umami Cloud allows 50 calls per 10 s
  const wait = 250 - (Date.now() - last)
  if (wait > 0) await sleep(wait)
  last = Date.now()
  const url = new URL(`${BASE}/websites/${share.websiteId}${path}`)
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, String(v))
  const res = await fetch(url, { headers: HEADERS })
  if (res.status === 429 && attempt < 4) {
    await sleep(2000 * (attempt + 1))
    return api(path, params, attempt + 1)
  }
  if (!res.ok) throw new Error(`${res.status} ${path}`)
  return res.json()
}

// The API only returns a window, so start early (LAUNCH_DATE-ish) unless --from is given. The first campaign
// visit decides the start of the report anyway; the rest is the untagged baseline.
const startAt = Date.parse(`${args.from ?? '2026-06-15'}T00:00:00Z`)
const endAt = Date.now()
const rows = []
for (let page = 1; page <= 300; page++) {
  const res = await api('/events', { startAt, endAt, hostname: args.hostname, page, pageSize: 100 })
  rows.push(...(res.data ?? []))
  if ((res.data ?? []).length < 100) break
  if (page === 300) throw new Error('stopped after 300 pages, event list is incomplete')
}
console.log(`${rows.length} event rows`)

// ---- visits ----
export function normalizeRef(query) {
  const m = /(?:^|&)ref=([^&]*)/.exec(query ?? '')
  if (!m) return null
  let v = m[1]
  try { v = decodeURIComponent(v.replace(/\+/g, ' ')) } catch {}
  // "…?ref=blog." happens when a link is copied with the full stop of the sentence it stood in
  v = v.trim().toLowerCase().replace(/[^a-z0-9]+$/, '')
  return aliases[v] ?? (v || null)
}

const byVisit = new Map()
for (const e of rows.sort((a, b) => a.createdAt.localeCompare(b.createdAt))) {
  if (!byVisit.has(e.visitId)) byVisit.set(e.visitId, [])
  byVisit.get(e.visitId).push(e)
}

const visits = [...byVisit.values()].map((evs) => {
  const pageviews = evs.filter((e) => e.eventType === 1 || !e.eventName)
  const names = new Set(evs.filter((e) => e.eventName).map((e) => e.eventName))
  const entry = pageviews[0] ?? evs[0]
  return {
    id: entry.visitId,
    session: entry.sessionId,
    t: Date.parse(entry.createdAt),
    day: dayKey(Date.parse(entry.createdAt)),
    ref: normalizeRef(entry.urlQuery) ?? pageviews.map((e) => normalizeRef(e.urlQuery)).find(Boolean) ?? null,
    mobile: entry.device === 'mobile',
    searched: names.has('search-started') || names.has('search-quick')
  }
})

// a visit counts as "returned" when the same session has a later visit
const sessionVisits = new Map()
for (const v of visits) (sessionVisits.get(v.session) ?? sessionVisits.set(v.session, []).get(v.session)).push(v.t)
for (const v of visits) v.returned = sessionVisits.get(v.session).some((t) => t > v.t)

const eventsFrom = Date.parse(`${EVENTS_TRACKING_DATE}T00:00:00+02:00`)

function metrics(list) {
  const n = list.length
  const tracked = list.filter((v) => v.t >= eventsFrom)
  const perDay = new Map()
  for (const v of list) perDay.set(v.day, (perDay.get(v.day) ?? 0) + 1)
  const peak = [...perDay.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0]
  return {
    visits: n,
    visitors: new Set(list.map((v) => v.session)).size,
    first: list.map((v) => v.day).sort()[0] ?? null,
    last: list.map((v) => v.day).sort().at(-1) ?? null,
    peak: peak ? { day: peak[0], visits: peak[1] } : null,
    mobile: list.filter((v) => v.mobile).length,
    // the search rate is taken over visits after events existed
    tracked: tracked.length,
    searched: tracked.filter((v) => v.searched).length,
    returned: list.filter((v) => v.returned).length
  }
}

// ---- report ----
const pct = (a, b) => (b ? `${Math.round((a / b) * 100)} %` : '–')
const rate = (a, b, n = b) => (b ? `${pct(a, b)}${n < MIN_VISITS ? ' †' : ''}` : '–')
// rate plus the absolute count, so a small channel with a good rate is not mistaken for a big one
const rateN = (a, b, n = b) => (b ? `${rate(a, b, n)} (${a})` : '–')
const dm = (iso) => (iso ? `${iso.slice(8, 10)}.${iso.slice(5, 7)}.` : '–')
// the first `left` columns are text, the rest numbers
const table = (head, body, left = 1) => [`| ${head.join(' | ')} |`, `|${head.map((_, i) => (i < left ? '---' : '---:')).join('|')}|`, ...body.map((r) => `| ${r.join(' | ')} |`)]

const ignoredRefs = new Set(registry.ignore ?? [])
const real = visits.filter((v) => !ignoredRefs.has(v.ref))
const tagged = real.filter((v) => v.ref)
const untagged = real.filter((v) => !v.ref)
const refs = [...new Set(tagged.map((v) => v.ref))]
const stats = Object.fromEntries(refs.map((r) => [r, metrics(tagged.filter((v) => v.ref === r))]))
refs.sort((a, b) => stats[b].visits - stats[a].visits)

const campaignRow = (name, m, meta = {}) => [
  name,
  meta.channel ?? '–',
  `${dm(meta.since ?? m.first)}–${dm(m.last)}`,
  m.visits,
  m.visitors,
  rateN(m.searched, m.tracked),
  rate(m.returned, m.visits),
  rate(m.mobile, m.visits),
  m.peak ? `${m.peak.visits} (${dm(m.peak.day)})` : '–'
]
const HEAD = ['Campaign', 'Channel', 'Active', 'Visits', 'Visitors', 'Searched', 'Returned', 'Mobile', 'Peak day']

const out = []
const today = dayKey(Date.now())
out.push(`Generated ${dm(today)}${today.slice(0, 4)} from Umami, ${rows.length} events, ${real.length} visits (${tagged.length} with a \`ref\`, ${untagged.length} without).`, '')

out.push('## Campaigns', '')
out.push(...table(HEAD, [
  ...refs.map((r) => campaignRow(registry.campaigns[r]?.label ?? `**${r}** (not in campaigns.json)`, stats[r], registry.campaigns[r])),
  campaignRow('*All untagged visits*', metrics(untagged))
], 3), '')
out.push(
  '- **Visits / Visitors**: visits (30 min of inactivity ends one) and distinct browsers. The `ref` counts on the entry page only; a returning visitor without a `ref` is untagged.',
  `- **Searched**: share of visits with at least one search, and how many that is. Measured over visits from ${dm(EVENTS_TRACKING_DATE)} on, when event tracking started (earlier visits only count towards Visits, e.g. the first Reddit day).`,
  '- **Returned**: the same browser came back in a later visit (within Umami\'s monthly session id).',
  `- † fewer than ${MIN_VISITS} visits: a rate from so few says nothing.`,
  ''
)

// warnings
const warnings = []
for (const r of refs) if (!registry.campaigns[r]) warnings.push(`unregistered ref \`${r}\` (${stats[r].visits} visits): add it to scripts/umami/campaigns.json`)
for (const r of Object.keys(registry.campaigns)) if (!stats[r]) warnings.push(`registered ref \`${r}\` has no visits in the data`)
const rawRefs = new Map()
for (const e of rows) {
  const m = /(?:^|&)ref=([^&]*)/.exec(e.urlQuery ?? '')
  if (m && e.eventType === 1) rawRefs.set(m[1], (rawRefs.get(m[1]) ?? 0) + 1)
}
const typos = [...rawRefs.keys()].filter((raw) => normalizeRef(`ref=${raw}`) !== raw.toLowerCase())
if (typos.length) warnings.push(`merged spellings: ${typos.map((t) => `\`${t}\` → \`${normalizeRef(`ref=${t}`)}\``).join(', ')}`)
if (warnings.length) out.push('## Data notes', '', ...warnings.map((w) => `- ${w}`), '')

const generated = out.join('\n').trimEnd()
if (args.dry) {
  console.log(generated)
} else {
  const existing = await readFile(REPORT, 'utf8').catch(() => null)
  const block = `${START}\n${generated}\n${END}`
  let next
  if (existing && existing.includes(START) && existing.includes(END)) {
    next = existing.slice(0, existing.indexOf(START)) + block + existing.slice(existing.indexOf(END) + END.length)
  } else {
    next = `# Marketing campaigns\n\nWhich tagged links (\`?ref=<name>\`) brought visitors, and what they did. Refresh with \`npm run umami:campaigns\`; the \`/campaign-report\` skill refreshes it and rewrites the findings.\n\n${block}\n\n## Findings\n\n(none yet)\n`
  }
  await writeFile(REPORT, next)
  console.log(`report: ${REPORT.pathname}`)
}
